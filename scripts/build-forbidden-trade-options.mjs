import crypto from "node:crypto";
import fs from "node:fs/promises";

const root = new URL("../", import.meta.url);
const sourceUrl = new URL("public/data/price-check/stats-v1.json", root);
const outputUrl = new URL("src/data/forbidden-trade-options.ts", root);
const sourceText = await fs.readFile(sourceUrl, "utf8");
const source = JSON.parse(sourceText);
const sidesByPassive = new Map();

for (const entry of source.entries || []) {
  for (const candidate of entry.candidates || []) {
    const text = String(candidate.ref || "");
    const match = /^Allocates (.+) if you have the matching modifier on Forbidden (Flame|Flesh)$/.exec(text);
    if (!match) continue;
    const id = String(candidate.id || "");
    const option = /\|(\d+)$/.exec(id)?.[1];
    if (!option) throw new Error(`Missing selector option for ${text}.`);
    const sides = sidesByPassive.get(match[1]) || new Map();
    sides.set(match[2], option);
    sidesByPassive.set(match[1], sides);
  }
}

const options = {};
for (const passive of [...sidesByPassive.keys()].sort((a, b) => a.localeCompare(b))) {
  const sides = sidesByPassive.get(passive);
  if (sides.size !== 2 || sides.get("Flame") !== sides.get("Flesh")) {
    throw new Error(`Forbidden selector mismatch for ${passive}.`);
  }
  options[passive] = sides.get("Flame");
}
if (Object.keys(options).length < 100) {
  throw new Error("Official stat pack yielded too few Forbidden passives.");
}

const generated = `// Generated by scripts/build-forbidden-trade-options.mjs. Do not hand-edit.\n` +
  `export const forbiddenTradeOptionsSource = ${JSON.stringify({
    generatedAt: source.generatedAt,
    statPackSha256: crypto.createHash("sha256").update(sourceText).digest("hex"),
  }, null, 2)} as const;\n\n` +
  `export const forbiddenPassiveTradeOptions: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(options, null, 2)});\n`;

await fs.mkdir(new URL("src/data/", root), { recursive: true });
await fs.writeFile(outputUrl, generated, "utf8");
console.log(`Wrote ${Object.keys(options).length} Forbidden passive selectors.`);
